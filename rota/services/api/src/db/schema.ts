import type { ColumnType, Generated, Insertable, Selectable, Updateable } from 'kysely';

// ─── Shared helpers ───────────────────────────────────────────────────────────

/** A column that is auto-generated by the DB and read-only for INSERT/UPDATE. */
type AutoColumn<T> = ColumnType<T, never, never>;
/** A timestamp column with a DB default; optional on insert. */
type TimestampWithDefault = ColumnType<Date, Date | undefined, Date>;
/** A timestamp column that is set only by the DB (now()), never by the app. */
type DbTimestamp = AutoColumn<Date>;

